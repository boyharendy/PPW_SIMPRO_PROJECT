CREATE FUNCTION app.anonymous_date() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME='complaint_messages' THEN
   IF NEW.sender_type='PELAPOR' THEN NEW.created_at:=CURRENT_DATE; END IF;
 ELSE
   IF TG_OP='INSERT' THEN NEW.created_at:=CURRENT_DATE; END IF;
   IF current_user='simpro_public' THEN NEW.updated_at:=CURRENT_DATE; END IF;
 END IF;
 RETURN NEW;
END $$;
