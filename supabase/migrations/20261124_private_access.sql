-- Assignment alone cannot disclose violence cases (FR-50).
CREATE OR REPLACE FUNCTION app.case_access(cid uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
 SELECT EXISTS (
   SELECT FROM complaints c WHERE c.id=cid AND (
     app.acting('PETUGAS_KEKERASAN')
     OR (app.acting('PENGELOLA_ADUAN') AND app.is_violence_handler())
     OR (NOT c.is_sensitif AND (app.acting('PENGELOLA_ADUAN','KAPRODI') OR app.has_active_disposition(cid)))
   )
 )
$$;

-- An owner-executed view must apply the object policy itself. Project the
-- metadata branch from a closed list so a future case column defaults to NULL.
CREATE VIEW simpro_visible_complaints WITH (security_barrier=true) AS
 SELECT c.* FROM complaints c WHERE app.case_access(c.id)
 UNION ALL
 SELECT masked.* FROM complaints c CROSS JOIN LATERAL jsonb_populate_record(NULL::complaints,
   jsonb_build_object('id',c.id,'nomor_aduan',c.nomor_aduan,'kategori',c.kategori,'status',c.status,
   'is_sensitif',true,'tanggal_pengaduan',c.tanggal_pengaduan,'tanggal_diterima',c.tanggal_diterima,
   'is_escalated_kaprodi',c.is_escalated_kaprodi,'created_at',c.tanggal_pengaduan::timestamptz)) masked
 WHERE c.is_sensitif AND app.acting('KAPRODI') AND NOT app.case_access(c.id);
REVOKE ALL ON simpro_visible_complaints FROM PUBLIC,anon,authenticated;
GRANT SELECT ON simpro_visible_complaints TO simpro_api;

