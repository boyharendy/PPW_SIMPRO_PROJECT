CREATE FUNCTION app.check_publication_verifier() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
 SET search_path=pg_catalog,public,pg_temp AS $$
BEGIN
 IF TG_OP='UPDATE' AND OLD.verifikator_id IS NOT DISTINCT FROM NEW.verifikator_id THEN RETURN NEW; END IF;
 IF NEW.verifikator_id IS NOT NULL AND (
   NEW.created_by=NEW.verifikator_id OR NOT app.eligible_lecturer(NEW.verifikator_id) OR
   (app.acting('KAPRODI') IS NOT TRUE AND NOT EXISTS (
     SELECT FROM publication_authors a WHERE a.publication_id=NEW.id AND a.user_id=NEW.verifikator_id
     AND a.tipe_penulis='DOSEN' AND a.peran IN ('PEMBIMBING','ANGGOTA','PENULIS_PENDAMPING'))))
 THEN RAISE EXCEPTION 'invalid publication verifier'; END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER assigned_verifier AFTER INSERT OR UPDATE OF verifikator_id ON publications
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.check_publication_verifier();
REVOKE ALL ON FUNCTION app.check_publication_verifier() FROM PUBLIC,anon,authenticated;

