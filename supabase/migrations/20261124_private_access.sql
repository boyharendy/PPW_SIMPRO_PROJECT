CREATE FUNCTION app.check_trip_budget() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
 SET search_path=pg_catalog,public,pg_temp AS $$
BEGIN
 IF NEW.sumber_dana IN ('RKA_PRODI','RKAT_PRODI','RKA') AND NOT EXISTS(
   SELECT FROM v_rka_pos_picker WHERE id=NEW.rka_budget_item_id)
 THEN RAISE EXCEPTION 'active budget line required'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER submitted_budget BEFORE UPDATE OF status ON travel_orders
 FOR EACH ROW WHEN (NEW.status='DIAJUKAN' AND OLD.status IS DISTINCT FROM NEW.status) EXECUTE FUNCTION app.check_trip_budget();
REVOKE ALL ON FUNCTION app.check_trip_budget() FROM PUBLIC,anon,authenticated;
