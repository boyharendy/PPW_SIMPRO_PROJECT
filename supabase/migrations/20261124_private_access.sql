CREATE FUNCTION app.process_complaint_deadlines(close_completed boolean) RETURNS integer
 LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE changed integer; verify_days jsonb; close_days integer;
BEGIN
 IF close_completed THEN
   SELECT coalesce((value#>>'{}')::integer,14) INTO close_days FROM app_settings WHERE key='autoclose_aduan_hari';
   UPDATE complaints SET status='DITUTUP',alasan_penutupan='Penutupan otomatis',tanggal_selesai=CURRENT_DATE
    WHERE status='SELESAI' AND coalesce(tanggal_penyelesaian,tanggal_selesai)<=CURRENT_DATE-coalesce(close_days,14);
 ELSE
   SELECT value INTO verify_days FROM app_settings WHERE key='aduan_sla_verifikasi_hari';
   UPDATE complaints c SET is_escalated_kaprodi=true,escalated_at=now()
    WHERE NOT is_escalated_kaprodi AND status NOT IN ('DITUTUP','SELESAI') AND
     (EXISTS (SELECT FROM complaint_dispositions d WHERE d.complaint_id=c.id AND d.status='AKTIF' AND d.deadline_tindak_lanjut<CURRENT_DATE)
      OR (status='DITERIMA' AND coalesce(tanggal_diterima,tanggal_pengaduan)<=CURRENT_DATE-
       CASE WHEN is_sensitif THEN coalesce((verify_days->>'sensitif')::integer,1) ELSE coalesce((verify_days->>'non_sensitif')::integer,3) END));
 END IF;
 GET DIAGNOSTICS changed=ROW_COUNT;RETURN changed;
END $$;
REVOKE ALL ON FUNCTION app.process_complaint_deadlines(boolean) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION app.process_complaint_deadlines(boolean) TO simpro_job;

